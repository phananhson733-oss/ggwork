/** 术语表的文本筛选：词条名、别名、正文、提示里任一处包含就留下（不区分大小写） */
export function filterGlossary(groups: readonly GlossaryGroup[], q: string): GlossaryGroup[] {
  const needle = q.trim().toLowerCase();
  if (!needle) return [...groups];
  return groups
    .map((g) => ({
      ...g,
      items: g.items.filter((it) => [it.t, it.a ?? "", it.d, it.h ?? ""].join(" ").toLowerCase().includes(needle)),
    }))
    .filter((g) => g.items.length > 0);
}
